-- Aikido Shinjukai student management: MERGED schema

DROP VIEW  IF EXISTS current_ranks;
DROP TABLE IF EXISTS payments CASCADE;
DROP TABLE IF EXISTS attendance CASCADE;
DROP TABLE IF EXISTS enrolments CASCADE;
DROP TABLE IF EXISTS sessions CASCADE;
DROP TABLE IF EXISTS classes CASCADE;
DROP TABLE IF EXISTS grading_rules CASCADE;
DROP TABLE IF EXISTS rank_history CASCADE;
DROP TABLE IF EXISTS users CASCADE;
DROP TABLE IF EXISTS ranks CASCADE;
DROP TABLE IF EXISTS centres CASCADE;

CREATE TABLE centres (
  id      INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name    TEXT NOT NULL,
  address TEXT
);

-- Students, instructors and admins all live here. A student's home centre is users.centre_id.
CREATE TABLE users (
  id                INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name              TEXT NOT NULL,
  email             TEXT NOT NULL UNIQUE,
  password_hash     TEXT NOT NULL,
  role              TEXT NOT NULL CHECK (role IN ('student', 'instructor', 'admin')),
  centre_id         INTEGER REFERENCES centres (id) ON DELETE SET NULL,
  date_of_birth     DATE,
  membership_status TEXT NOT NULL DEFAULT 'active' CHECK (membership_status IN ('active', 'inactive')), -- students only
  joined_on         DATE NOT NULL DEFAULT CURRENT_DATE,                                                  -- students only
  created_at        TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE ranks (
  id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name       TEXT NOT NULL UNIQUE,
  sort_order INTEGER NOT NULL UNIQUE CHECK (sort_order > 0) -- higher = more senior
);

-- A student's current rank is their latest row here (see the current_ranks view below).
CREATE TABLE rank_history (
  id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  student_id INTEGER NOT NULL REFERENCES users (id) ON DELETE CASCADE,
  rank_id    INTEGER NOT NULL REFERENCES ranks (id) ON DELETE RESTRICT,
  awarded_on DATE NOT NULL
);

CREATE TABLE classes (
  id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  centre_id     INTEGER NOT NULL REFERENCES centres (id) ON DELETE RESTRICT,
  instructor_id INTEGER NOT NULL REFERENCES users (id) ON DELETE RESTRICT,
  name          TEXT NOT NULL,
  day_of_week   SMALLINT NOT NULL CHECK (day_of_week BETWEEN 1 AND 7), -- ISO: 1 = Monday ... 7 = Sunday
  start_time    TIME NOT NULL,
  end_time      TIME NOT NULL,
  min_rank_id   INTEGER REFERENCES ranks (id) ON DELETE SET NULL,
  capacity      INTEGER NOT NULL DEFAULT 20 CHECK (capacity > 0),   -- added
  fee_cents     INTEGER NOT NULL DEFAULT 0 CHECK (fee_cents >= 0),  -- added
  CHECK (start_time < end_time)
);

-- Added a surrogate id and a status so payments can point at one enrolment.
CREATE TABLE enrolments (
  id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  student_id  INTEGER NOT NULL REFERENCES users (id) ON DELETE CASCADE,
  class_id    INTEGER NOT NULL REFERENCES classes (id) ON DELETE CASCADE,
  status      TEXT NOT NULL DEFAULT 'pending_payment' CHECK (status IN ('pending_payment', 'active')),
  enrolled_on DATE NOT NULL DEFAULT CURRENT_DATE,
  UNIQUE (student_id, class_id)
);

-- Only in the other design, so kept as-is (one payment per enrolment).
CREATE TABLE payments (
  id                INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  enrolment_id      INTEGER NOT NULL UNIQUE REFERENCES enrolments (id) ON DELETE CASCADE,
  stripe_session_id TEXT,
  amount_cents      INTEGER NOT NULL CHECK (amount_cents >= 0),
  status            TEXT NOT NULL DEFAULT 'unpaid' CHECK (status IN ('unpaid', 'paid')),
  paid_at           TIMESTAMPTZ
);

CREATE TABLE sessions (
  id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  class_id      INTEGER REFERENCES classes (id) ON DELETE RESTRICT,
  centre_id     INTEGER REFERENCES centres (id) ON DELETE SET NULL,
  date          DATE NOT NULL,
  start_time    TIME NOT NULL,
  end_time      TIME NOT NULL,
  type          TEXT NOT NULL CHECK (type IN ('regular', 'external')),
  external_name TEXT,
  CHECK (start_time < end_time),
  -- Regular sessions happen for a class; external sessions name an outside event.
  CONSTRAINT sessions_type_target CHECK (
    (type = 'regular' AND class_id IS NOT NULL)
    OR (type = 'external' AND external_name IS NOT NULL)
  )
);

CREATE TABLE attendance (
  id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  session_id INTEGER NOT NULL REFERENCES sessions (id) ON DELETE CASCADE,
  student_id INTEGER NOT NULL REFERENCES users (id) ON DELETE CASCADE,
  status     TEXT NOT NULL CHECK (status IN ('present', 'late', 'absent', 'excused')),
  marked_by  INTEGER REFERENCES users (id) ON DELETE SET NULL,
  marked_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
  UNIQUE (session_id, student_id)
);

CREATE TABLE grading_rules (
  id                  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  from_rank_id        INTEGER NOT NULL REFERENCES ranks (id) ON DELETE CASCADE,
  to_rank_id          INTEGER NOT NULL REFERENCES ranks (id) ON DELETE CASCADE,
  min_sessions        INTEGER NOT NULL CHECK (min_sessions >= 0),
  min_months_in_rank  INTEGER NOT NULL CHECK (min_months_in_rank >= 0),
  counts_external     BOOLEAN NOT NULL DEFAULT FALSE,
  min_age             INTEGER CHECK (min_age IS NULL OR min_age >= 0),
  active              BOOLEAN NOT NULL DEFAULT TRUE,
  UNIQUE (from_rank_id, to_rank_id)
);

-- Convenience view (new): each student's current rank and the date they received it.
-- Replaces the old students.belt_level and students.rank_since columns.
CREATE VIEW current_ranks AS
SELECT DISTINCT ON (rh.student_id)
       rh.student_id, rh.rank_id, r.name AS rank_name, r.sort_order, rh.awarded_on AS rank_since
  FROM rank_history rh
  JOIN ranks r ON r.id = rh.rank_id
 ORDER BY rh.student_id, rh.awarded_on DESC, rh.id DESC;

-- Latest-rank lookups scan by student; eligibility checks join on it too.
CREATE INDEX idx_rank_history_student_id ON rank_history (student_id);
CREATE INDEX idx_attendance_student_id ON attendance (student_id);
CREATE INDEX idx_sessions_date ON sessions (date);
CREATE INDEX idx_enrolments_class_id ON enrolments (class_id);